// ===== ilike/like検索のワイルドカード文字エスケープ =====
// 2026-08-14新設。外部総合品質監査レポート★2 L-06対応。
// Postgresの ilike('col', `%${q}%`) パターンは、ユーザー入力qに含まれる`%`・`_`を
// ワイルドカード文字としてそのまま解釈してしまう（エスケープされない）。
// データが他人に見える漏洩系の問題ではない（RLSで可視範囲は別途制限済み）が、
// 例えば氏名に「50%」のような文字列が含まれる場合や、単純に検索欄へ`%`を含む文字列を
// 入力した場合に、本人の意図より広い（または狭い・0件の）検索結果になってしまうUX上の不具合。
// ilikeへ渡す直前に、この関数でエスケープしてから`%`で挟むこと。
export function escapeLikePattern(input: string): string {
  return input.replace(/[%_\\]/g, ch => `\\${ch}`)
}
